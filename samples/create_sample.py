# Creates a synthetic 802.11 Beacon frame in binary format.

beacon = bytes([
    # 24-byte Management Header
    0x80, 0x00,
    0x00, 0x00,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xAA, 0xBB, 0xCC, 0x11, 0x22, 0x33,
    0xAA, 0xBB, 0xCC, 0x11, 0x22, 0x33,
    0x10, 0x00,

    # 12-byte Beacon Fixed Parameters
    0xE8, 0x03, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x64, 0x00,
    0x31, 0x04,

    # SSID Information Element: TEST
    0x00, 0x04, 0x54, 0x45, 0x53, 0x54,

    # Supported Rates Information Element
    0x01, 0x03, 0x82, 0x84, 0x8B,

    # DS Parameter Set: Channel 6
    0x03, 0x01, 0x06
])

with open("samples/beacon_sample.bin", "wb") as file:
    file.write(beacon)

print("Beacon sample created successfully.")
print("Total bytes:", len(beacon))